var checks = 0
func check(_ value: Bool, _ description: String) { precondition(value, description); checks += 1 }
let now = Date(timeIntervalSince1970: 1_800_000_000)
let good = FriendSnapshot(id: UUID(), name: "QA friend", generatedAt: now, weekStart: "2026-09-23", weekEnd: "2026-09-29", days: ["Work": 3], followers: ["linkedin": 3000], followerDates: ["linkedin": now], tokens: ["codex": 50_000_000])
check(good.valid(now: now), "Real-shaped snapshot validates")
var bad = good; bad.days["Work"] = 8; check(!bad.valid(now: now), "More than seven activity days rejected")
bad = good; bad.tokens["codex"] = -1; check(!bad.valid(now: now), "Negative tokens rejected")
bad = good; bad.followers["linkedin"] = -1; check(!bad.valid(now: now), "Negative followers rejected")
bad = good; bad.followerDates = [:]; check(!bad.valid(now: now), "Undated follower counts rejected")
bad = good; bad.generatedAt = now.addingTimeInterval(121); check(!bad.valid(now: now), "Future snapshots rejected")
bad = good; bad.version = 2; check(!bad.valid(now: now), "Unknown schema rejected")
bad = good; bad.name = String(repeating: "x", count: 61); check(!bad.valid(now: now), "Oversized name rejected")
bad = good; bad.tokens["made-up"] = 500; check(!bad.valid(now: now), "Unknown token source rejected")
bad = good; bad.weekStart = "yesterday"; check(!bad.valid(now: now), "Unparseable day rejected")
bad = good; bad.weekStart = "2026-10-01"; check(!bad.valid(now: now), "Inverted window rejected")
bad = good; bad.followers = [:]; bad.followerDates = [:]; bad.tokens = [:]; check(bad.valid(now: now), "Unshared fields stay absent")
let restored = try JSONDecoder().decode(FriendSnapshot.self, from: JSONEncoder().encode(good))
check(restored.valid(now: now) && restored.tokens["codex"] == 50_000_000, "Snapshot round trip preserves source counts")
print("PASS: \(checks) friend snapshot checks")
